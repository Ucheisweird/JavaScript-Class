// only checks the value of the variable
var num1 = 12 ;
var num2 = '12';
var res = num1 == num2 ;
console.log(res); // true

var num1 = 12 ;
var num2 = '12';
var res = num1 != num2 ;
console.log(res); // false

// strict operators (!== , ===)
// it checks the value and data types of the variable

var num1 = 12 ;
var num2 = '12';
var res = num1 === num2 ;
console.log(res); // false

var num1 = 12 ;
var num2 = '12';
var res = num1 != num2 ;
console.log(res); // true




