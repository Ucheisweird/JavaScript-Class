var num = 10
/// pre - Decrement op (--Variable)
console.log (--num); // num-1 = 9
console.log (--num); // 8
console.log (--num); // 7

console.log('====================')
// post decrement op (variable --)
var val = 10;
console.log(val--); // val -0 =10
console.log(val--); // 9
console.log(val--); // 8
console.log(val--); // 7
console.log(val--); // 6
console.log(val--); // 5
