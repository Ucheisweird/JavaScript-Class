/// plus for string concatenation 
var userName = 'peter'
var userAge = 34

var strData = userName + userAge // peter 34
console.log(strData)

// plus op for adding numbers 
var numOfEggs = 30
var numOfBread = 45
var totalItems = numOfEggs + numOfBread // 75
console.log(totalItems)

// for auto conversion 
var age = '12' // type string 
var myAge = +age // type number 
console.log(myAge)